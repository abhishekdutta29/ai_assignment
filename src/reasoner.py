"""
KnowledgeLens - Module 2: Symbolic Reasoning Engine
Integrates 5 classical Symbolic AI reasoning techniques:
1. Direct Triple Lookup (Fact Retrieval - O(1))
2. Graph Search (BFS/DFS Transitive Traversal & Reachability - O(V+E))
3. Forward Chaining (Data-Driven Horn Clause Deduction)
4. Backward Chaining (Goal-Driven Proof Tree Generation)
5. Constraint Aggregation (Counting, Summation, Filtering, Comparison)
Produces full explainable reasoning traces with provenance.
"""

from typing import List, Dict, Tuple, Any, Optional, Set
from src.kb import KnowledgeBase, Triple
from src.question_parser import StructuredQuery
from src.inference_rules import StudentProfile, get_all_inference_rules, HornRule

class ReasoningTrace:
    """Detailed explainable record of the symbolic inference process."""
    def __init__(self,
                 technique_name: str,
                 technique_rationale: str,
                 query_summary: Dict[str, Any]):
        self.technique_name = technique_name
        self.technique_rationale = technique_rationale
        self.query_summary = query_summary
        self.steps: List[str] = []
        self.rules_fired: List[str] = []
        self.supporting_triples: List[Dict[str, Any]] = []
        self.highlight_nodes: List[str] = []
        self.highlight_edges: List[Dict[str, str]] = []
        self.proof_tree: Optional[Dict[str, Any]] = None
        self.time_complexity: str = ""

    def add_step(self, step: str):
        self.steps.append(step)

    def add_triple(self, triple: Triple):
        t_dict = triple.to_dict()
        if t_dict not in self.supporting_triples:
            self.supporting_triples.append(t_dict)
            self.highlight_nodes.append(triple.subject)
            self.highlight_nodes.append(triple.object)
            self.highlight_edges.append({
                "from": triple.subject,
                "to": triple.object,
                "label": triple.predicate
            })

    def to_dict(self) -> Dict[str, Any]:
        return {
            "technique_name": self.technique_name,
            "technique_rationale": self.technique_rationale,
            "query_summary": self.query_summary,
            "steps": self.steps,
            "rules_fired": self.rules_fired,
            "supporting_triples": self.supporting_triples,
            "highlight_nodes": list(set(self.highlight_nodes)),
            "highlight_edges": self.highlight_edges,
            "proof_tree": self.proof_tree,
            "time_complexity": self.time_complexity
        }


class ReasoningResult:
    """The complete result generated by the symbolic reasoning engine."""
    def __init__(self,
                 status: str,  # "SUCCESS", "NOT_FOUND", "AMBIGUOUS"
                 answer_payload: Any,
                 trace: ReasoningTrace,
                 closest_suggestions: Optional[List[str]] = None):
        self.status = status
        self.answer_payload = answer_payload
        self.trace = trace
        self.closest_suggestions = closest_suggestions or []

    def to_dict(self) -> Dict[str, Any]:
        return {
            "status": self.status,
            "answer_payload": self.answer_payload,
            "trace": self.trace.to_dict(),
            "closest_suggestions": self.closest_suggestions
        }


class ReasoningEngine:
    """
    Classical Symbolic Reasoning Engine routing queries to appropriate inference mechanisms.
    """
    def __init__(self, kb: KnowledgeBase):
        self.kb = kb
        self.inference_rules = get_all_inference_rules()

    def reason(self, query: StructuredQuery, profile: Optional[StudentProfile] = None, enable_rules: bool = True) -> ReasoningResult:
        """Dispatches structured query to the appropriate symbolic reasoning strategy."""
        student_prof = profile or StudentProfile()

        # Handle unanswerable questions gracefully
        if query.qtype == "UNANSWERABLE" or (not query.entities and not query.predicate and not query.constraints):
            return self._handle_unanswerable(query)

        # Route by query type
        if query.qtype == "TRANSITIVE_CHAIN":
            return self._reason_transitive_chain(query)
        elif query.qtype == "REACHABILITY":
            return self._reason_reachability(query)
        elif query.qtype == "FORWARD_INFERENCE":
            if not enable_rules:
                return self._ablation_rules_disabled(query)
            return self._reason_forward_chaining(query, student_prof)
        elif query.qtype == "BACKWARD_PROOF":
            if not enable_rules:
                return self._ablation_rules_disabled(query)
            return self._reason_backward_chaining(query, student_prof)
        elif query.qtype in ["AGGREGATION_COUNT", "AGGREGATION_SUM", "FILTER_LIST"]:
            return self._reason_aggregation(query)
        elif query.qtype == "COMPARISON":
            return self._reason_comparison(query)
        else:
            # Default to Direct Fact Lookup
            return self._reason_direct_lookup(query)

    def _handle_unanswerable(self, query: StructuredQuery) -> ReasoningResult:
        trace = ReasoningTrace(
            technique_name="Grounding & Domain Boundary Verification",
            technique_rationale="Evaluated query entities and relations against the Knowledge Base schema.",
            query_summary=query.to_dict()
        )
        trace.add_step("Scanned input tokens for grounded canonical entities and domain relations.")
        trace.add_step("No valid entities or relations matched within the closed-world Knowledge Base.")
        trace.time_complexity = "O(1) lexical lookup"

        # Provide nearest known suggestions
        all_canonical = list(self.kb.entity_index.canonical_entities)[:6]
        return ReasoningResult(
            status="NOT_FOUND",
            answer_payload={"message": "Not found in the knowledge base."},
            trace=trace,
            closest_suggestions=all_canonical
        )

    def _ablation_rules_disabled(self, query: StructuredQuery) -> ReasoningResult:
        trace = ReasoningTrace(
            technique_name="Ablation: Inference Rules Disabled",
            technique_rationale="Inference engine is running in raw Triple-Only mode; Horn clause inference is disabled.",
            query_summary=query.to_dict()
        )
        trace.add_step("Ablation mode active: Forward/Backward chaining rules are deactivated.")
        return ReasoningResult(
            status="NOT_FOUND",
            answer_payload={"message": "Query requires rule-based inference, which is currently disabled in this ablation run."},
            trace=trace,
            closest_suggestions=[]
        )

    # --------------------------------------------------------------------------
    # TECHNIQUE 1: Direct Triple Lookup
    # --------------------------------------------------------------------------
    def _reason_direct_lookup(self, query: StructuredQuery) -> ReasoningResult:
        trace = ReasoningTrace(
            technique_name="Direct Triple Store Lookup",
            technique_rationale="Single-hop factual query mapped directly to indexed (Subject, Predicate, Object) store.",
            query_summary=query.to_dict()
        )
        trace.time_complexity = "O(1) hash table lookup"

        entity = query.entities[0] if query.entities else None
        predicate = query.predicate

        trace.add_step(f"Target Entity: '{entity}', Target Predicate: '{predicate}'")

        # 1. Subject + Predicate lookup (iterate through linked entities by confidence)
        candidate_entities = query.entities if query.entities else [None]
        candidate_preds = [predicate] if predicate else []
        if predicate == "credits":
            candidate_preds.append("degree_credits")
        elif predicate == "definition" or "what is" in query.raw_question.lower() or "define" in query.raw_question.lower():
            candidate_preds.extend(["is_a_branch_of", "is_part_of", "purpose", "behavior", "has_title"])

        for entity in candidate_entities:
            if not entity:
                continue
            for p in candidate_preds:
                triples = self.kb.triple_store.find(subject=entity, predicate=p)
                if not triples and p in ["taught_by", "teaches"]:
                    # Try inverse relation
                    triples = self.kb.triple_store.find(obj=entity, predicate="taught_by" if p == "teaches" else "teaches")
                if not triples:
                    # Also check object position
                    triples = self.kb.triple_store.find(obj=entity, predicate=p)

                if triples:
                    for t in triples:
                        trace.add_triple(t)
                        trace.rules_fired.append(t.rule_id)
                    trace.add_step(f"Retrieved {len(triples)} matching triple(s) for '{entity}' and '{p}'.")
                    return ReasoningResult("SUCCESS", {"triples": [t.to_dict() for t in triples]}, trace)

        # 2. Subject only lookup
        if entity and not predicate:
            triples = self.kb.triple_store.find(subject=entity)
            if triples:
                for t in triples:
                    trace.add_triple(t)
                    trace.rules_fired.append(t.rule_id)
                trace.add_step(f"Retrieved all {len(triples)} facts for subject '{entity}'.")
                return ReasoningResult("SUCCESS", {"triples": [t.to_dict() for t in triples]}, trace)

        # 3. Predicate only lookup (strictly for domain policies, thresholds, and deadlines)
        if predicate and predicate in ["minimum_requirement", "threshold", "deadline", "course_load", "degree_credits"]:
            triples = self.kb.triple_store.find(predicate=predicate)
            if triples:
                # If question specifically mentions attendance, filter to attendance
                q_raw = query.raw_question.lower()
                if "attendance" in q_raw:
                    triples = [t for t in triples if "attendance" in t.subject.lower()] or triples
                elif "pass mark" in q_raw:
                    triples = [t for t in triples if "pass" in t.subject.lower()] or triples

                for t in triples:
                    trace.add_triple(t)
                    trace.rules_fired.append(t.rule_id)
                trace.add_step(f"Retrieved {len(triples)} facts matching predicate '{predicate}'.")
                return ReasoningResult("SUCCESS", {"triples": [t.to_dict() for t in triples]}, trace)

        # Not found
        trace.add_step("No triples matched the query parameters in the indexed store.")
        return ReasoningResult(
            status="NOT_FOUND",
            answer_payload={"message": "Not found in the knowledge base."},
            trace=trace,
            closest_suggestions=list(self.kb.entity_index.canonical_entities)[:5]
        )

    # --------------------------------------------------------------------------
    # TECHNIQUE 2: Graph Search (Transitive Dependencies & Reachability)
    # --------------------------------------------------------------------------
    def _reason_transitive_chain(self, query: StructuredQuery) -> ReasoningResult:
        trace = ReasoningTrace(
            technique_name="Graph Search: BFS Transitive Dependency Traversal",
            technique_rationale="Query asks for transitive multi-hop dependencies (e.g. all prerequisites in curriculum hierarchy).",
            query_summary=query.to_dict()
        )
        trace.time_complexity = "O(V + E) Breadth-First Search"

        target_course = query.entities[0] if query.entities else None
        if not target_course:
            trace.add_step("Failed to identify valid target course entity.")
            return ReasoningResult("NOT_FOUND", {"message": "Not found in the knowledge base."}, trace)

        trace.add_step(f"Beginning breadth-first traversal from root course '{target_course}'.")
        deps, edges, steps = self.kb.graph.find_transitive_dependencies(target_course, relation="prerequisite")
        for s in steps:
            trace.add_step(s)

        for u, rel, v, triple in edges:
            trace.add_triple(triple)
            trace.rules_fired.append(triple.rule_id)

        if deps:
            trace.add_step(f"Traversal complete: identified {len(deps)} transitive prerequisite course(s).")
            return ReasoningResult(
                status="SUCCESS",
                answer_payload={
                    "target_course": target_course,
                    "prerequisites": deps,
                    "chain_length": len(deps)
                },
                trace=trace
            )
        else:
            trace.add_step(f"Course '{target_course}' has no prerequisites recorded in the Knowledge Graph.")
            return ReasoningResult(
                status="SUCCESS",
                answer_payload={
                    "target_course": target_course,
                    "prerequisites": [],
                    "chain_length": 0
                },
                trace=trace
            )

    def _reason_reachability(self, query: StructuredQuery) -> ReasoningResult:
        trace = ReasoningTrace(
            technique_name="Graph Search: Shortest Path Reachability (BFS)",
            technique_rationale="Evaluates directed reachability between two course nodes to verify prerequisite ordering.",
            query_summary=query.to_dict()
        )
        trace.time_complexity = "O(V + E) BFS Path Verification"

        if len(query.entities) < 2:
            trace.add_step("Reachability verification requires at least two identified entities.")
            return ReasoningResult("NOT_FOUND", {"message": "Not found in the knowledge base."}, trace)

        c1 = query.entities[0]
        c2 = query.entities[1]

        trace.add_step(f"Checking reachability between '{c1}' and '{c2}' along prerequisite relations.")
        reachable, path, reason_msg = self.kb.graph.check_reachability(c1, c2, relation="prerequisite")

        if path:
            for u, rel, v, triple in path:
                trace.add_triple(triple)
                trace.rules_fired.append(triple.rule_id)
                trace.add_step(f"Verified hop: {u} -> {v} (via {triple.raw_text})")

        trace.add_step(f"Reachability determination: {reason_msg}")
        return ReasoningResult(
            status="SUCCESS",
            answer_payload={
                "source": c1,
                "target": c2,
                "is_reachable": reachable,
                "path_length": len(path) if path else 0,
                "message": reason_msg
            },
            trace=trace
        )

    # --------------------------------------------------------------------------
    # TECHNIQUE 3: Forward Chaining with Horn Clauses
    # --------------------------------------------------------------------------
    def _reason_forward_chaining(self, query: StructuredQuery, profile: StudentProfile) -> ReasoningResult:
        trace = ReasoningTrace(
            technique_name="Forward Chaining (Horn Clause Deduction)",
            technique_rationale="Data-driven inference applying institutional policies against factual student profile state.",
            query_summary=query.to_dict()
        )
        trace.time_complexity = "O(R * F) Rule matching over factual memory"

        q_lower = query.raw_question.lower()
        target_course = query.entities[0] if query.entities else None

        trace.add_step(f"Initial Factual State: Student ID '{profile.student_id}', Completed Courses: {profile.completed_courses}, Attendance: {profile.attendance}%, CGPA: {profile.cgpa}, Credits: {profile.completed_credits}.")

        # Case A: Capstone eligibility
        if "capstone" in q_lower or (target_course and target_course == "AI499"):
            rule = next(r for r in self.inference_rules if r.rule_id == "RULE_CAPSTONE_ELIGIBILITY")
            fired, explanation, evidence = rule.evaluate(profile, self.kb, "AI499")
            trace.rules_fired.append(rule.rule_id)
            trace.add_step(f"Applied Rule '{rule.name}': {explanation}")
            for ev in evidence:
                trace.supporting_triples.append(ev)
            return ReasoningResult(
                status="SUCCESS",
                answer_payload={"eligible": fired, "course": "AI499", "explanation": explanation},
                trace=trace
            )

        # Case B: Dean's Honour List
        if "dean" in q_lower or "honour" in q_lower:
            rule = next(r for r in self.inference_rules if r.rule_id == "RULE_DEANS_HONOUR_LIST")
            fired, explanation, evidence = rule.evaluate(profile, self.kb)
            trace.rules_fired.append(rule.rule_id)
            trace.add_step(f"Applied Rule '{rule.name}': {explanation}")
            for ev in evidence:
                trace.supporting_triples.append(ev)
            return ReasoningResult(
                status="SUCCESS",
                answer_payload={"qualifies": fired, "honor": "Dean's Honour List", "explanation": explanation},
                trace=trace
            )

        # Case C: Academic probation
        if "probation" in q_lower or "standing" in q_lower:
            rule = next(r for r in self.inference_rules if r.rule_id == "RULE_ACADEMIC_PROBATION")
            on_probation, explanation, evidence = rule.evaluate(profile, self.kb)
            trace.rules_fired.append(rule.rule_id)
            trace.add_step(f"Applied Rule '{rule.name}': {explanation}")
            for ev in evidence:
                trace.supporting_triples.append(ev)
            return ReasoningResult(
                status="SUCCESS",
                answer_payload={"on_probation": on_probation, "explanation": explanation},
                trace=trace
            )

        # Case D: Exam eligibility / attendance
        if "exam" in q_lower or "attendance" in q_lower or "examination" in q_lower or "barred" in q_lower:
            rule = next(r for r in self.inference_rules if r.rule_id == "RULE_EXAM_ATTENDANCE")
            can_exam, explanation, evidence = rule.evaluate(profile, self.kb)
            trace.rules_fired.append(rule.rule_id)
            trace.add_step(f"Applied Rule '{rule.name}': {explanation}")
            for ev in evidence:
                trace.supporting_triples.append(ev)
            return ReasoningResult(
                status="SUCCESS",
                answer_payload={"eligible_for_exam": can_exam, "explanation": explanation},
                trace=trace
            )

        # Case E: Specific course eligibility
        if target_course and self.kb.entity_index.entity_categories.get(target_course) in ["Course", "CourseTitle", "General"]:
            rule = next(r for r in self.inference_rules if r.rule_id == "RULE_COURSE_ELIGIBILITY")
            fired, explanation, evidence = rule.evaluate(profile, self.kb, target_course)
            trace.rules_fired.append(rule.rule_id)
            trace.add_step(f"Applied Rule '{rule.name}': {explanation}")
            for ev in evidence:
                trace.supporting_triples.append(ev)
            return ReasoningResult(
                status="SUCCESS",
                answer_payload={"eligible": fired, "course": target_course, "explanation": explanation},
                trace=trace
            )

        # Case F: General forward sweep - find all courses student is currently eligible to take
        rule = next(r for r in self.inference_rules if r.rule_id == "RULE_COURSE_ELIGIBILITY")
        all_courses = [nid for nid, info in self.kb.graph.nodes.items() if info.get("category") == "Course"]
        eligible_courses = []
        for c in sorted(all_courses):
            if c not in profile.completed_courses:
                ok, _, _ = rule.evaluate(profile, self.kb, c)
                if ok:
                    eligible_courses.append(c)

        trace.add_step(f"Forward sweep complete across {len(all_courses)} courses. Identified {len(eligible_courses)} eligible courses.")
        return ReasoningResult(
            status="SUCCESS",
            answer_payload={"eligible_courses": eligible_courses},
            trace=trace
        )

    # --------------------------------------------------------------------------
    # TECHNIQUE 4: Backward Chaining (Proof Tree Construction)
    # --------------------------------------------------------------------------
    def _reason_backward_chaining(self, query: StructuredQuery, profile: StudentProfile) -> ReasoningResult:
        trace = ReasoningTrace(
            technique_name="Backward Chaining (Goal-Driven Proof Tree)",
            technique_rationale="Goal-directed resolution proving assertion by recursively decomposing into grounded facts.",
            query_summary=query.to_dict()
        )
        trace.time_complexity = "O(b^d) Proof tree resolution (bounded by rule base depth)"

        q_lower = query.raw_question.lower()
        target_course = query.entities[0] if query.entities else None

        # Build Proof Tree
        if "barred" in q_lower or "exam" in q_lower:
            goal_desc = f"barred_from_exam(Student '{profile.student_id}')"
            trace.add_step(f"Established root goal: {goal_desc}")

            rule = next(r for r in self.inference_rules if r.rule_id == "RULE_EXAM_ATTENDANCE")
            threshold = 75.0
            actual_att = profile.attendance
            is_barred = actual_att < threshold

            subgoals = [
                {
                    "subgoal": f"attendance(Student) < {threshold}%",
                    "status": "PROVED" if is_barred else "REFUTED",
                    "fact": f"Student attendance is {actual_att}% (Policy requires >= {threshold}%)"
                }
            ]

            proof_tree = {
                "goal": goal_desc,
                "status": "PROVED" if is_barred else "REFUTED",
                "rule_applied": rule.name,
                "conclusion": f"Student is {'BARRED from' if is_barred else 'CLEARED for'} examination.",
                "subgoals": subgoals
            }
            trace.proof_tree = proof_tree
            trace.rules_fired.append(rule.rule_id)
            trace.add_step(f"Proof resolved: {proof_tree['conclusion']}")

            return ReasoningResult(
                status="SUCCESS",
                answer_payload={"proved": is_barred, "proof_tree": proof_tree},
                trace=trace
            )

        # Default course eligibility proof
        target = target_course or "AI301"
        goal_desc = f"eligible_for(Student '{profile.student_id}', Course '{target}')"
        trace.add_step(f"Established root goal: {goal_desc}")

        prereq_triples = self.kb.triple_store.find(subject=target, predicate="prerequisite")
        prereqs = [t.object for t in prereq_triples]
        for t in prereq_triples:
            trace.add_triple(t)

        subgoals = []
        all_proved = True
        for p in prereqs:
            completed = p in profile.completed_courses
            if not completed:
                all_proved = False
            subgoals.append({
                "subgoal": f"completed_course(Student, '{p}')",
                "status": "PROVED" if completed else "REFUTED",
                "fact": f"Course '{p}' is {'in' if completed else 'NOT in'} completed courses list."
            })

        proof_tree = {
            "goal": goal_desc,
            "status": "PROVED" if all_proved else "REFUTED",
            "rule_applied": "RULE_COURSE_ELIGIBILITY",
            "conclusion": f"Goal is {'PROVED (Student is eligible)' if all_proved else 'REFUTED (Prerequisites incomplete)'}",
            "subgoals": subgoals
        }
        trace.proof_tree = proof_tree
        trace.rules_fired.append("RULE_COURSE_ELIGIBILITY")
        trace.add_step(f"Proof tree synthesized with {len(subgoals)} subgoals.")

        return ReasoningResult(
            status="SUCCESS",
            answer_payload={"proved": all_proved, "proof_tree": proof_tree},
            trace=trace
        )

    # --------------------------------------------------------------------------
    # TECHNIQUE 5: Constraint Aggregations (Count, Sum, Filter, Comparison)
    # --------------------------------------------------------------------------
    def _reason_aggregation(self, query: StructuredQuery) -> ReasoningResult:
        trace = ReasoningTrace(
            technique_name="Symbolic Constraint & Aggregation Engine",
            technique_rationale="Iterates indexed triple relations applying filter predicate, distinct set grouping, and aggregation.",
            query_summary=query.to_dict()
        )
        trace.time_complexity = "O(N) linear filter over indexed relation triples"

        q_lower = query.raw_question.lower()

        # 1. Total credits for semester
        if "semester" in query.constraints and ("sum" in q_lower or "total credit" in q_lower):
            sem = query.constraints["semester"]
            sem_triples = self.kb.triple_store.find(predicate="offered_in", obj=sem)
            total_credits = 0
            courses_included = []

            for st in sem_triples:
                trace.add_triple(st)
                c_code = st.subject
                cr_triples = self.kb.triple_store.find(subject=c_code, predicate="credits")
                if cr_triples:
                    trace.add_triple(cr_triples[0])
                    val = int(cr_triples[0].object)
                    total_credits += val
                    courses_included.append(f"{c_code} ({val} cr)")

            trace.add_step(f"Calculated sum of credits for {sem}: {total_credits} across {len(courses_included)} courses.")
            return ReasoningResult(
                status="SUCCESS",
                answer_payload={
                    "semester": sem,
                    "total_credits": total_credits,
                    "courses": courses_included
                },
                trace=trace
            )

        # 2. Filter courses by semester
        if "semester" in query.constraints:
            sem = query.constraints["semester"]
            triples = self.kb.triple_store.find(predicate="offered_in", obj=sem)
            courses = [t.subject for t in triples]
            for t in triples:
                trace.add_triple(t)
            trace.add_step(f"Filtered {len(courses)} course(s) offered in {sem}.")
            return ReasoningResult(
                status="SUCCESS",
                answer_payload={"semester": sem, "courses": courses, "count": len(courses)},
                trace=trace
            )

        # 3. Filter courses taught by instructor
        instructor = next((e for e in query.entities if "Prof" in e or "Dr" in e or self.kb.entity_index.entity_categories.get(e) == "Instructor"), None)
        if instructor:
            triples = self.kb.triple_store.find(predicate="taught_by", obj=instructor)
            if not triples:
                triples = self.kb.triple_store.find(subject=instructor, predicate="teaches")
            courses = [t.subject if t.predicate == "taught_by" else t.object for t in triples]
            for t in triples:
                trace.add_triple(t)
            trace.add_step(f"Retrieved {len(courses)} course(s) assigned to '{instructor}'.")
            return ReasoningResult(
                status="SUCCESS",
                answer_payload={"instructor": instructor, "courses": courses, "count": len(courses)},
                trace=trace
            )

        # 4. Filter courses by Department
        dept = next((e for e in query.entities if "Department" in e or self.kb.entity_index.entity_categories.get(e) == "Department"), None)
        if dept:
            triples = self.kb.triple_store.find(predicate="department", obj=dept)
            courses = [t.subject for t in triples]
            for t in triples:
                trace.add_triple(t)
            trace.add_step(f"Retrieved {len(courses)} course(s) belonging to '{dept}'.")
            return ReasoningResult(
                status="SUCCESS",
                answer_payload={"department": dept, "courses": courses, "count": len(courses)},
                trace=trace
            )

        # Default count of prerequisites or general facts
        if query.entities and query.predicate == "prerequisite":
            c = query.entities[0]
            triples = self.kb.triple_store.find(subject=c, predicate="prerequisite")
            for t in triples:
                trace.add_triple(t)
            return ReasoningResult(
                status="SUCCESS",
                answer_payload={"course": c, "prerequisites": [t.object for t in triples], "count": len(triples)},
                trace=trace
            )

        return self._reason_direct_lookup(query)

    def _reason_comparison(self, query: StructuredQuery) -> ReasoningResult:
        trace = ReasoningTrace(
            technique_name="Symbolic Entity Property Comparison",
            technique_rationale="Extracts numerical properties of two distinct entities and computes relational delta.",
            query_summary=query.to_dict()
        )
        trace.time_complexity = "O(1) dual property lookup and comparison"

        if len(query.entities) < 2:
            trace.add_step("Comparison requires at least two identified entities.")
            return ReasoningResult("NOT_FOUND", {"message": "Not found in the knowledge base."}, trace)

        e1, e2 = query.entities[0], query.entities[1]
        t1 = self.kb.triple_store.find(subject=e1, predicate="credits")
        t2 = self.kb.triple_store.find(subject=e2, predicate="credits")

        if t1 and t2:
            trace.add_triple(t1[0])
            trace.add_triple(t2[0])
            c1_val = int(t1[0].object)
            c2_val = int(t2[0].object)

            if c1_val > c2_val:
                verdict = f"{e1} ({c1_val} credits) carries more credits than {e2} ({c2_val} credits)."
            elif c2_val > c1_val:
                verdict = f"{e2} ({c2_val} credits) carries more credits than {e1} ({c1_val} credits)."
            else:
                verdict = f"Both {e1} and {e2} carry the exact same number of credits ({c1_val} credits)."

            trace.add_step(f"Comparison calculated: {verdict}")
            return ReasoningResult(
                status="SUCCESS",
                answer_payload={"entity1": e1, "credits1": c1_val, "entity2": e2, "credits2": c2_val, "verdict": verdict},
                trace=trace
            )

        trace.add_step(f"Failed to find credit values for both entities '{e1}' and '{e2}'.")
        return ReasoningResult("NOT_FOUND", {"message": "Not found in the knowledge base."}, trace)
